"""Generate discovery manifests from skills/ and registry/. Never hand-edit the outputs.

  build.py           write outputs
  build.py --check   exit 1 if outputs are stale (used in CI)

Outputs:
  .claude-plugin/marketplace.json   one plugin per group + one per bundle
  docs/CATALOG.md                   human-readable catalog
"""
import json
import os
import sys

from common import ROOT, parse_frontmatter, registries, skills_in_group

OWNER = {"name": "Texas Instruments Incorporated"}


def skill_path(group, skill):
    return "./skills/%s/%s" % (group, skill)


def build_marketplace(regs):
    plugins = []
    for group, reg in regs.items():
        skills = skills_in_group(group)
        if not skills:
            continue
        plugins.append({
            "name": group,
            "description": reg["description"].strip().split("\n")[0],
            "source": "./",
            "strict": False,
            "skills": [skill_path(group, s) for s in skills],
        })
        for bname, b in (reg.get("bundles") or {}).items():
            plugins.append({
                "name": "%s-%s" % (group, bname),
                "description": b["description"],
                "source": "./",
                "strict": False,
                "skills": [skill_path(group, s) for s in b["skills"]],
            })
    return {
        "name": "ti-agentic-skills",
        "owner": OWNER,
        "metadata": {"description": "Agent Skills for Texas Instruments products and software."},
        "plugins": plugins,
    }


def build_catalog(regs):
    out = ["<!-- Generated by tools/build.py. Do not edit. -->", "# Skill catalog", ""]
    for group, reg in regs.items():
        out += ["## %s" % reg["name"], "",
                "`%s` - status: %s - license: %s" % (group, reg["status"], reg["license"]), "",
                reg["description"].strip(), ""]
        skills = skills_in_group(group)
        if not skills:
            out += ["_No skills published yet._", ""]
            continue
        out += ["| Skill | Description |", "|---|---|"]
        for s in skills:
            fm, _ = parse_frontmatter(os.path.join(ROOT, "skills", group, s, "SKILL.md"))
            d = " ".join(str(fm.get("description", "")).split())
            if len(d) > 160:
                d = d[:157] + "..."
            out.append("| `%s` | %s |" % (s, d.replace("|", "\\|")))
        out.append("")
        bundles = reg.get("bundles") or {}
        if bundles:
            out += ["Bundles:", ""]
            for bname, b in bundles.items():
                out.append("- `%s-%s`: %s (%s)" % (group, bname, b["description"],
                                                  ", ".join(b["skills"])))
            out.append("")
    return "\n".join(out)


def main():
    check = "--check" in sys.argv[1:]
    regs = registries()
    outputs = {
        ".claude-plugin/marketplace.json": json.dumps(build_marketplace(regs), indent=2) + "\n",
        "docs/CATALOG.md": build_catalog(regs) + "\n",
    }
    stale = 0
    for rel, text in outputs.items():
        p = os.path.join(ROOT, rel)
        cur = open(p, encoding="utf-8").read() if os.path.isfile(p) else None
        if cur == text:
            continue
        if check:
            print("build: stale %s (run tools/build.py)" % rel, file=sys.stderr)
            stale += 1
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(text)
            print("wrote " + rel)
    if stale:
        return 1
    if check:
        print("build: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
